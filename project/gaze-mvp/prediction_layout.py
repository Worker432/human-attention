"""Presentation and controls for the native attention preview."""
from pathlib import Path
from PySide6.QtCore import Qt
from PySide6.QtGui import QKeySequence, QShortcut
from PySide6.QtWidgets import (QAbstractItemView, QCheckBox, QFormLayout, QFrame,
    QComboBox, QHBoxLayout, QHeaderView, QLabel, QPushButton, QScrollArea, QSlider, QSpinBox,
    QTableWidget, QTabWidget, QToolButton, QVBoxLayout, QWidget)


def build_interface(panel, canvas_type):
    base = Path(__file__).resolve().parent
    panel.setObjectName("predictionWindow")
    panel.setWindowTitle("Прогноз внимания")
    panel.resize(1280, 850)
    panel.setMinimumSize(940, 650)
    style = (base / "prediction_style.qss").read_text()
    panel.setStyleSheet(style.replace("__CHECK_ICON__", str(base / "icons/check.svg")))
    layout = QVBoxLayout(panel)
    layout.setContentsMargins(28, 23, 28, 21)
    layout.setSpacing(19)

    header = QHBoxLayout()
    titles = QVBoxLayout()
    titles.setSpacing(5)
    title = QLabel("Прогноз внимания")
    title.setObjectName("pageTitle")
    titles.addWidget(title)
    subtitle = QLabel("Как может двигаться взгляд по вашему изображению")
    subtitle.setObjectName("subtitle")
    titles.addWidget(subtitle)
    header.addLayout(titles, 1)
    panel.open_button = QPushButton("Открыть изображение…")
    panel.open_button.setToolTip("Выбрать файл · ⌘O")
    panel.open_button.clicked.connect(panel.open_image)
    header.addWidget(panel.open_button)
    panel.export_button = QPushButton("Сохранить…")
    panel.export_button.setToolTip("Сохранить изображение с прогнозом · ⌘S")
    panel.export_button.clicked.connect(panel.export_image)
    header.addWidget(panel.export_button)
    panel.gallery_button = QPushButton('Общая heatmap')
    panel.gallery_button.setToolTip('Объединить 30 вариантов взгляда в одну тепловую карту')
    panel.gallery_button.clicked.connect(panel.open_gallery)
    header.addWidget(panel.gallery_button)
    layout.addLayout(header)

    body = QHBoxLayout()
    body.setSpacing(20)
    stage = QVBoxLayout()
    stage.setSpacing(12)
    panel.filename = QLabel("Выберите изображение или перетащите его в окно")
    panel.filename.setObjectName("fileName")
    panel.filename.setTextFormat(Qt.TextFormat.PlainText)
    panel.filename.setWordWrap(True)
    file_row = QHBoxLayout()
    file_row.addWidget(panel.filename, 1)
    panel.batch_button = QPushButton('Обработать папку…')
    panel.batch_button.clicked.connect(panel.open_batch)
    file_row.addWidget(panel.batch_button)
    stage.addLayout(file_row)
    panel.canvas = canvas_type()
    panel.canvas.image_dropped.connect(lambda path: panel.set_image(Path(path)))
    stage.addWidget(panel.canvas, 1)
    layers = QHBoxLayout()
    layers.setContentsMargins(2, 0, 2, 0)
    panel.boxes = QCheckBox("Объекты")
    panel.boxes.setToolTip("Показать найденные рамки и классы объектов")
    layers.addWidget(panel.boxes)
    layers.addSpacing(16)
    panel.route = QCheckBox("Маршрут")
    panel.route.setChecked(True)
    layers.addWidget(panel.route)
    layers.addSpacing(16)
    panel.heatmap = QCheckBox("Heatmap")
    panel.heatmap.setToolTip("Тепловая карта предсказанных точек: тёплые цвета показывают их скопления")
    layers.addWidget(panel.heatmap)
    layers.addStretch()
    stage.addLayout(layers)
    panel.heat_controls = QWidget()
    heat_layout = QVBoxLayout(panel.heat_controls)
    heat_layout.setContentsMargins(2, 0, 2, 0)
    heat_controls = QHBoxLayout()
    heat_layout.addLayout(heat_controls)
    panel.heat_mode = QComboBox()
    panel.heat_mode.addItems(["Скопления точек маршрута", "Вероятность отдельного шага", "Общая по 30 вариантам"])
    heat_controls.addWidget(panel.heat_mode)
    heat_controls.addStretch()
    heat_controls.addWidget(QLabel("Интенсивность"))
    panel.opacity = QSlider(Qt.Orientation.Horizontal)
    panel.opacity.setRange(10, 100)
    panel.opacity.setValue(65)
    panel.opacity.setFixedWidth(100)
    panel.opacity.setAccessibleName("Непрозрачность тепловой карты")
    heat_controls.addWidget(panel.opacity)
    save_heatmap = QPushButton("Сохранить heatmap…")
    save_heatmap.setToolTip("Только исходное изображение и тепловая карта, без подписей и рамок")
    save_heatmap.clicked.connect(panel.export_heatmap)
    heat_footer = QHBoxLayout()
    heat_footer.addStretch()
    heat_footer.addWidget(save_heatmap)
    heat_layout.addLayout(heat_footer)
    panel.heat_controls.hide()
    stage.addWidget(panel.heat_controls)
    for control in (panel.boxes, panel.route, panel.heatmap):
        control.toggled.connect(panel.toggle_layers)
    panel.opacity.valueChanged.connect(panel.toggle_layers)
    panel.heat_mode.currentIndexChanged.connect(panel.toggle_layers)
    playback = QHBoxLayout()
    playback.setSpacing(15)
    panel.play_button = QPushButton("Смотреть маршрут")
    panel.play_button.setProperty("primary", True)
    panel.play_button.setToolTip("Воспроизвести или приостановить · пробел")
    panel.play_button.clicked.connect(panel.play)
    playback.addWidget(panel.play_button)
    panel.slider = QSlider(Qt.Orientation.Horizontal)
    panel.slider.setRange(0, 8)
    panel.slider.setAccessibleName("Шаг предсказанной последовательности")
    panel.slider.sliderPressed.connect(panel.stop)
    panel.slider.valueChanged.connect(panel.seek)
    playback.addWidget(panel.slider, 1)
    panel.step_label = QLabel("0 из 8")
    panel.step_label.setObjectName("stepCount")
    panel.step_label.setAlignment(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter)
    playback.addWidget(panel.step_label)
    stage.addLayout(playback)
    body.addLayout(stage, 1)

    inspector = QFrame()
    inspector.setObjectName("inspector")
    side = QVBoxLayout(inspector)
    side.setContentsMargins(21, 22, 21, 21)
    side.setSpacing(12)
    eyebrow = QLabel("ПРОГНОЗ МОДЕЛИ")
    eyebrow.setObjectName("eyebrow")
    side.addWidget(eyebrow)
    heading = QLabel("Внимание на баннере")
    heading.setObjectName("sectionTitle")
    side.addWidget(heading)
    panel.result_summary = QLabel("Сначала выберите изображение")
    panel.result_summary.setObjectName("resultSummary")
    panel.result_summary.setWordWrap(True)
    side.addWidget(panel.result_summary)
    panel.sequence = QTableWidget(0, 4)
    panel.sequence.setHorizontalHeaderLabels(["№", "Координаты", "Область", "Сопоставление"])
    panel.sequence.setColumnHidden(1, True)
    panel.sequence.setColumnHidden(3, True)
    panel.sequence.horizontalHeader().hide()
    panel.sequence.verticalHeader().hide()
    panel.sequence.setColumnWidth(0, 37)
    panel.sequence.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeMode.Fixed)
    panel.sequence.horizontalHeader().setSectionResizeMode(2, QHeaderView.ResizeMode.Stretch)
    panel.sequence.verticalHeader().setDefaultSectionSize(43)
    panel.sequence.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
    panel.sequence.setSelectionMode(QAbstractItemView.SelectionMode.SingleSelection)
    panel.sequence.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
    panel.sequence.setShowGrid(False)
    panel.sequence.setMinimumHeight(160)
    panel.sequence.setMaximumHeight(375)
    panel.sequence.currentCellChanged.connect(panel.sequence_selected)
    tabs = QTabWidget()
    tabs.addTab(panel.sequence, 'Маршрут')
    objects_page = QWidget()
    objects_layout = QVBoxLayout(objects_page)
    objects_layout.setContentsMargins(0, 8, 0, 0)
    panel.object_table = QTableWidget(0, 3)
    panel.object_table.setHorizontalHeaderLabels(['Область', 'Точек', '%'])
    panel.object_table.verticalHeader().hide()
    panel.object_table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
    panel.object_table.setShowGrid(False)
    panel.object_table.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeMode.Stretch)
    panel.object_table.setColumnWidth(1, 47)
    panel.object_table.setColumnWidth(2, 49)
    objects_layout.addWidget(panel.object_table, 1)
    note_objects = QLabel('Доля предсказанных точек, не время просмотра. Рамки могут пропускать объекты.')
    note_objects.setWordWrap(True)
    note_objects.setObjectName('caption')
    objects_layout.addWidget(note_objects)
    panel.metrics_button = QPushButton('Сохранить CSV…')
    panel.metrics_button.clicked.connect(panel.export_metrics)
    objects_layout.addWidget(panel.metrics_button)
    tabs.addTab(objects_page, 'Объекты')
    side.addWidget(tabs, 1)
    panel.variant_button = QPushButton("Показать другой маршрут")
    panel.variant_button.setToolTip("Построить ещё один возможный вариант просмотра")
    panel.variant_button.clicked.connect(panel.another_variant)
    side.addWidget(panel.variant_button)
    panel.predict_button = QPushButton("Построить прогноз")
    panel.predict_button.setProperty("primary", True)
    panel.predict_button.clicked.connect(panel.predict)
    side.addWidget(panel.predict_button)
    panel.cancel_button = QPushButton('Остановить расчёт')
    panel.cancel_button.clicked.connect(panel.cancel_prediction)
    panel.cancel_button.hide()
    side.addWidget(panel.cancel_button)
    panel.status = QLabel("Начните с изображения. Камера не нужна.")
    panel.status.setObjectName("status")
    panel.status.setTextFormat(Qt.TextFormat.PlainText)
    panel.status.setWordWrap(True)
    side.addWidget(panel.status)
    panel.settings_toggle = QToolButton()
    panel.settings_toggle.setText("Параметры и детали")
    panel.settings_toggle.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonTextBesideIcon)
    panel.settings_toggle.setArrowType(Qt.ArrowType.RightArrow)
    panel.settings_toggle.setCheckable(True)
    side.addWidget(panel.settings_toggle)
    panel.advanced = QWidget()
    form = QFormLayout(panel.advanced)
    form.setContentsMargins(0, 0, 0, 8)
    form.setSpacing(10)
    panel.steps = QSpinBox()
    panel.steps.setRange(1, 20)
    panel.steps.setValue(8)
    panel.steps.setSuffix(" точек")
    panel.steps.setAccessibleName("Длина маршрута")
    form.addRow("Длина маршрута", panel.steps)
    panel.seed = QSpinBox()
    panel.seed.setRange(0, 999999)
    panel.seed.setValue(42)
    panel.seed.setAccessibleName("Номер варианта")
    form.addRow("Номер варианта", panel.seed)
    panel.step_detail = QLabel("Выберите точку маршрута")
    panel.step_detail.setObjectName("stepDetail")
    panel.step_detail.setWordWrap(True)
    form.addRow(panel.step_detail)
    models = QLabel("Взгляд: DeepGaze III\nОбъекты: YOLO11m\nНачальная позиция: центр")
    models.setObjectName("caption")
    form.addRow(models)
    panel.advanced.hide()
    panel.settings_toggle.toggled.connect(lambda expanded: (
        panel.advanced.setVisible(expanded), panel.settings_toggle.setArrowType(
            Qt.ArrowType.DownArrow if expanded else Qt.ArrowType.RightArrow)))
    side.addWidget(panel.advanced)
    note = QLabel("Один из возможных вариантов просмотра. Паузы анимации условные — длительность взгляда не рассчитывается.")
    note.setObjectName("caption")
    note.setWordWrap(True)
    side.addWidget(note)
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    scroll.setMinimumWidth(300)
    scroll.setMaximumWidth(320)
    scroll.setWidget(inspector)
    body.addWidget(scroll)
    layout.addLayout(body, 1)

    panel.steps.valueChanged.connect(panel.parameters_changed)
    panel.seed.valueChanged.connect(panel.parameters_changed)
    panel.shortcuts = [QShortcut(QKeySequence.StandardKey.Open, panel, activated=panel.open_image),
                       QShortcut(QKeySequence.StandardKey.Save, panel, activated=panel.save_shortcut),
                       QShortcut(QKeySequence("Space"), panel, activated=panel.play)]
